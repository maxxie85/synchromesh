#!/usr/bin/env python3
"""Writes build/icon/AppIcon.svg: the brass synchro ring with the red download arrow.

The teeth and rings are computed, so change the numbers below rather than the SVG. Then run make-icns.sh and
commit the SVG and its outputs.
"""
import math
import os

BODY, RING, RING_SHADOW, GROOVE, FACE, ARROW = "#F4F5F8", "#D4AA4A", "#B08A35", "#E6C774", "#E1E4EC", "#E8394A"
CX = CY = 512
TEETH, ROOT_R, TIP_R = 28, 322, 366       # chamfered teeth around the ring
BAND_R, FACE_R = 300, 236                 # the shadowed band inside the teeth, and the face
GROOVES = [(274, 262), (250, 242)]        # the cone's grooves (outer, inner radius)


def f(v):
    return f"{v:.1f}"


def gear(teeth, r_root, r_tip, rotation_deg, tip_frac, base_frac, steps):
    """A closed outline with trapezoid teeth; tooth i is centred at rotation + i * 360 / teeth."""
    pitch, rot, pts = 2 * math.pi / teeth, math.radians(rotation_deg), []
    for i in range(teeth):
        c = rot + i * pitch
        b0, b1 = c - pitch * base_frac / 2, c + pitch * base_frac / 2
        t0, t1 = c - pitch * tip_frac / 2, c + pitch * tip_frac / 2
        nxt = c + pitch - pitch * base_frac / 2
        pts.append((b0, r_root))
        pts += [(t0 + (t1 - t0) * k / steps, r_tip) for k in range(steps + 1)]
        pts.append((b1, r_root))
        pts += [(b1 + (nxt - b1) * k / steps, r_root) for k in range(1, steps)]
    return "M " + " L ".join(f"{f(CX + r * math.cos(a))} {f(CY + r * math.sin(a))}" for a, r in pts) + " Z"


def circle(r, hole=False):
    """A circle as two arcs; a hole runs the other way (used with fill-rule evenodd)."""
    s = 0 if hole else 1
    return f"M {f(CX - r)} {f(CY)} A {f(r)} {f(r)} 0 1 {s} {f(CX + r)} {f(CY)} A {f(r)} {f(r)} 0 1 {s} {f(CX - r)} {f(CY)} Z"


def ring(outer_path, inner_r, fill):
    return f'<path d="{outer_path} {circle(inner_r, hole=True)}" fill="{fill}" fill-rule="evenodd"/>'


# Arrow: shaft and head, centred a little below the middle so it looks centred.
aw, ah, shaft = 236, 300, 78
top, bottom = CY + 6 - ah / 2, CY + 6 + ah / 2
head_top = bottom - ah * 0.48

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Synchromesh app icon, flat style: the brass synchro ring of a gearbox's synchromesh, face on, with its chamfered
       teeth and the grooves of its cone, and a red download arrow through the middle. The light body and the red
       follow the earlier icon (Transmission's red plunger handle).
       Drawn on Apple's 1024 grid: 824 px body at 100,100, leaving room for the drop shadow that render-svg.swift
       adds. Solid colours only (AppKit's SVG renderer, used for the build, ignores filters anyway).
       Generated by build/icon/make-svg.py: edit that, not this file. Then run make-icns.sh and commit the outputs. -->

  <!-- Body -->
  <rect x="100" y="100" width="824" height="824" rx="185" fill="{BODY}"/>

  <!-- Ring: teeth, the shadowed band inside them, the cone's grooves, and the face -->
  {ring(gear(TEETH, ROOT_R, TIP_R, -90, tip_frac=0.30, base_frac=0.72, steps=2), FACE_R, RING)}
  {ring(circle(BAND_R), FACE_R, RING_SHADOW)}
  {chr(10).join("  " + ring(circle(o), i, GROOVE) for o, i in GROOVES).lstrip()}
  <circle cx="{CX}" cy="{CY}" r="{FACE_R}" fill="{FACE}"/>

  <!-- Arrow -->
  <rect x="{f(CX - shaft / 2)}" y="{f(top)}" width="{f(shaft)}" height="{f(head_top - top + 4)}" rx="{f(shaft * 0.22)}" fill="{ARROW}"/>
  <path d="M {f(CX - aw / 2)} {f(head_top)} L {f(CX + aw / 2)} {f(head_top)} L {f(CX)} {f(bottom)} Z" fill="{ARROW}" stroke="{ARROW}" stroke-width="22" stroke-linejoin="round"/>
</svg>
'''

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "AppIcon.svg")
with open(out, "w") as handle:
    handle.write(svg)
print(f"Wrote {out}")
